    T.shape(ellipse_pts(cx, cy, 30, 30, 16), '#ffd43b', lw=6)
    if u > 1.2: label(c, f'{int(pv)}%', cx, cy - 150, 110, '#ffd43b', 0, 1)
    label(c, 'LIES SPOTTED', cx, 220, 60, '#ffffff', 0, back((u - 0.8)/0.3, 1.4))

